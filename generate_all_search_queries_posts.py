def generate_and_update_all():
    count = 0
    for post_id, article_info in ARTICLES_DATA.items():
        file_path = os.path.join(POSTS_DIR, f"{post_id}.json")
        data = {}
        if os.path.exists(file_path):
            try:
                with open(file_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
            except Exception:
                data = {}
        
        # データを上書き・個別完全最適化
        data["id"] = post_id
        data["hinban"] = article_info["hinban"]
        data["title"] = article_info["title"]
        data["labels"] = article_info["labels"]
        data["review"] = article_info["review"]
        if "date" not in data:
            data["date"] = "2026-08-13 14:00:00"
            
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        
        print(f"Generated/Updated article: {file_path}")
        count += 1

    print(f"\nSuccessfully generated/updated {count} custom articles for Search Console queries.")

