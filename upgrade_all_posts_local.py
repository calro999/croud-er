def generate_combinatorial_review(title):
    intro = random.choice(intros)
    body = random.choice(bodies)
    bullet = random.choice(bullets)
    review = random.choice(reviews)
    qa = random.choice(qas)
    conclusion = random.choice(conclusions)
    
    html = f"<h2>【超絶話題作】『{title}』の全貌と圧倒的魅力に迫る！</h2>\n"
    html += intro + "\n"
    html += body + "\n"
    html += bullet + "\n"
    html += review + "\n"
    html += qa + "\n"
    html += conclusion
    return html

def upgrade_all_posts_local():
    files = glob.glob(os.path.join(POSTS_DIR, "*.json"))
    upgraded_count = 0
    
    for file_path in files:
        with open(file_path, "r", encoding="utf-8") as f:
            try:
                data = json.load(f)
            except:
                continue
                
        title = data.get("title", "本作")
        
        # JSON内のreviewを完全な独自HTMLに差し替える
        new_review = generate_combinatorial_review(title)
        data["review"] = new_review
        
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            
        upgraded_count += 1
            
    print(f"Total upgraded locally: {upgraded_count}")

if __name__ == "__main__":
    upgrade_all_posts_local()
